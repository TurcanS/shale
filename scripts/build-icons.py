#!/usr/bin/env python3
"""Build core/icons.js from assets/icons/*.svg so the Icon component can draw any glyph in any colour.

Every icon is a 24-unit, 1.6-stroke outline whose stroke is the one colour Icon replaces. Run again after
adding or editing an SVG; --check fails when icons.js is out of date.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets" / "icons"
TARGET = ROOT / "core" / "icons.js"
HEADER = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#f2f2f2" '
          'stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round">')

TEMPLATE = """.pragma library

// Generated by scripts/build-icons.py from assets/icons; do not edit by hand.

const shapes = {shapes};

// A data URL drawing the named icon with the given stroke colour (a QML color), or "" for an unknown name.
function url(name, color) {{
    const shape = shapes[name];
    if (shape === undefined)
        return "";
    const hex = "#" + [color.r, color.g, color.b].map(value => Math.round(value * 255).toString(16).padStart(2, "0")).join("");
    return "data:image/svg+xml;utf8," + encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="'
        + hex + '" stroke-opacity="' + color.a + '" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round">' + shape + "</svg>");
}}
"""


def build():
    shapes = {}
    for path in sorted(SOURCE.glob("*.svg")):
        text = path.read_text().strip()
        if not text.startswith(HEADER) or not text.endswith("</svg>"):
            raise SystemExit(f"{path.name}: expected the shared 24-unit outline header")
        inner = text[len(HEADER):-len("</svg>")]
        if re.search(r'(fill|stroke)="#', inner):
            raise SystemExit(f"{path.name}: shapes must not set their own colour")
        shapes[path.stem] = inner
    return TEMPLATE.format(shapes=json.dumps(shapes, indent=4, ensure_ascii=False))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if core/icons.js is out of date")
    args = parser.parse_args()
    output = build()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text() != output:
            raise SystemExit("core/icons.js is out of date; run scripts/build-icons.py")
        return
    TARGET.write_text(output)
    print(f"Wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
