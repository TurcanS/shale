#!/usr/bin/env python3
"""Build core/icons.js from assets/icons/*.svg so the Icon component can draw any glyph in any colour.

Every icon is a 24-unit outline with round caps and joins. Its shapes become SVG path data, grouped into at most
three layers by stroke width and opacity, which Icon draws as vector paths: no image loading, any colour, sharp at
any size. Run again after adding or editing an SVG; --check fails when icons.js is out of date.
"""
import argparse
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets" / "icons"
TARGET = ROOT / "core" / "icons.js"
SVG = "{http://www.w3.org/2000/svg}"
LAYERS = 3

TEMPLATE = """.pragma library

// Generated by scripts/build-icons.py from assets/icons; do not edit by hand.
// Each icon is a list of layers: {{w: stroke width, o: opacity, d: SVG path data}} in a 24-unit box.

var shapes = {shapes};
"""


def number(value):
    return f"{float(value):g}"


NUMBER = re.compile(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")


def absolute_start(data):
    """A path's first moveto is absolute even when written "m"; paths joined into one layer must say so, or the
    joined path would place it relative to the previous one. Pairs after it are relative linetos."""
    data = data.strip()
    if not data.startswith("m"):
        return data
    x = NUMBER.search(data, 1)
    y = NUMBER.search(data, x.end())
    rest = data[y.end():].lstrip(" ,")
    return f"M{x.group()} {y.group()}" + ("l" + rest if rest and rest[0] not in "MmLlHhVvCcSsQqTtAaZz" else rest)


def outline(element):
    tag = element.tag.removeprefix(SVG)
    get = lambda name, default="0": float(element.get(name, default))
    if tag == "path":
        return absolute_start(element.get("d"))
    if tag in ("circle", "ellipse"):
        cx, cy = get("cx"), get("cy")
        rx = get("r") if tag == "circle" else get("rx")
        ry = get("r") if tag == "circle" else get("ry")
        return (f"M{number(cx - rx)} {number(cy)}a{number(rx)} {number(ry)} 0 1 0 {number(2 * rx)} 0"
                f"a{number(rx)} {number(ry)} 0 1 0 {number(-2 * rx)} 0z")
    if tag == "rect":
        x, y, w, h = get("x"), get("y"), get("width"), get("height")
        rx = min(get("rx", element.get("ry", "0")), w / 2)
        ry = min(get("ry", element.get("rx", "0")), h / 2)
        if not rx or not ry:
            return f"M{number(x)} {number(y)}h{number(w)}v{number(h)}h{number(-w)}z"
        arc = lambda dx, dy: f"a{number(rx)} {number(ry)} 0 0 1 {number(dx)} {number(dy)}"
        return (f"M{number(x + rx)} {number(y)}h{number(w - 2 * rx)}{arc(rx, ry)}v{number(h - 2 * ry)}{arc(-rx, ry)}"
                f"h{number(-(w - 2 * rx))}{arc(-rx, -ry)}v{number(-(h - 2 * ry))}{arc(rx, -ry)}z")
    raise ValueError(f"unsupported element <{tag}>")


def icon(path):
    root = ET.parse(path).getroot()
    expected = {"viewBox": "0 0 24 24", "fill": "none", "stroke-linecap": "round", "stroke-linejoin": "round"}
    if any(root.get(key) != value for key, value in expected.items()):
        raise SystemExit(f"{path.name}: expected the shared 24-unit outline header")
    width = float(root.get("stroke-width", "1.6"))
    layers = {}
    for element in root:
        if element.get("fill", "none") != "none" or "stroke" in element.attrib:
            raise SystemExit(f"{path.name}: shapes must not set their own fill or colour")
        try:
            data = outline(element)
        except ValueError as error:
            raise SystemExit(f"{path.name}: {error}")
        key = (float(element.get("stroke-width", width)), float(element.get("opacity", "1")))
        layers.setdefault(key, []).append(data)
    if len(layers) > LAYERS:
        raise SystemExit(f"{path.name}: at most {LAYERS} stroke width and opacity combinations")
    return [{"w": w, "o": o, "d": "".join(parts)} for (w, o), parts in layers.items()]


def build():
    shapes = {path.stem: icon(path) for path in sorted(SOURCE.glob("*.svg"))}
    return TEMPLATE.format(shapes=json.dumps(shapes, indent=4, ensure_ascii=False))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if core/icons.js is out of date")
    args = parser.parse_args()
    output = build()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text() != output:
            raise SystemExit("core/icons.js is out of date; run scripts/build-icons.py")
        return
    TARGET.write_text(output)
    print(f"Wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
